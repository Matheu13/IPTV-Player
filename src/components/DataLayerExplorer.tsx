// Subcomponent for each stream row with thumbnail generator service
const M3uStreamRowItem: React.FC<{
  channel: UnifiedChannel;
  isSelected: boolean;
  onSelect: () => void;
  onInspect: () => void;
}> = ({ channel, isSelected, onSelect, onInspect }) => {
  const [thumbUrl, setThumbUrl] = useState<string | null>(null);
  const [loadingThumb, setLoadingThumb] = useState(true);

  const streamUrl = channel.resolvedStreamUrl || (channel as any).directSourceUrl || '';

  useEffect(() => {
    let isMounted = true;
    setLoadingThumb(true);

    globalThumbnailService
      .getThumbnail(streamUrl, channel.name, channel.streamIcon)
      .then((url) => {
        if (isMounted && url) {
          setThumbUrl(url);
        }
      })
      .finally(() => {
        if (isMounted) setLoadingThumb(false);
      });

    return () => {
      isMounted = false;
    };
  }, [streamUrl, channel.name, channel.streamIcon]);

  return (
    <div
      onClick={onSelect}
      className={`p-3 rounded-xl border transition cursor-pointer flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3 ${
        isSelected
          ? 'bg-amber-950/30 border-amber-500/60 shadow-lg shadow-amber-950/20'
          : 'bg-slate-950/70 border-slate-800/80 hover:bg-slate-800/50 hover:border-slate-700'
      }`}
    >
      <div className="flex items-center gap-3.5 min-w-0">
        {/* Stream Thumbnail generated by service */}
        <div className="relative w-24 h-14 rounded-lg overflow-hidden bg-slate-900 border border-slate-800 shrink-0 flex items-center justify-center group/thumb">
          {thumbUrl ? (
            <img
              src={thumbUrl}
              alt={channel.name}
              className="w-full h-full object-cover"
              onError={() => setThumbUrl(null)}
            />
          ) : (
            <div className="flex flex-col items-center justify-center text-slate-600 gap-1">
              <Tv className="w-5 h-5 text-amber-400/70" />
              <span className="text-[9px] font-mono">1080p</span>
            </div>
          )}

          {/* Mini Resolution Badge */}
          <span className="absolute top-1 right-1 bg-black/80 text-[8px] font-mono font-bold text-cyan-300 px-1 py-0.2 rounded border border-white/10">
            {channel.name.includes('60FPS') ? '60FPS' : 'FHD'}
          </span>
        </div>

        {/* Channel Details */}
        <div className="min-w-0 space-y-0.5">
          <div className="flex items-center gap-2">
            <span className="text-xs font-bold text-slate-100 truncate">{channel.name}</span>
            {channel.categoryName && (
              <span className="text-[10px] font-mono bg-slate-800 text-slate-300 px-1.5 py-0.2 rounded shrink-0">
                {channel.categoryName}
              </span>
            )}
          </div>
          <p className="text-[11px] font-mono text-slate-400 truncate max-w-sm sm:max-w-md" title={streamUrl}>
            {streamUrl}
          </p>
          <div className="flex items-center gap-2 text-[10px] font-mono text-slate-400">
            <span>ID: {channel.epgChannelId || channel.id}</span>
            <span>•</span>
            <span className="text-emerald-400">Ready for Ingest</span>
          </div>
        </div>
      </div>

      {/* Action Buttons */}
      <div className="flex items-center gap-2 self-end sm:self-auto shrink-0" onClick={(e) => e.stopPropagation()}>
        <button
          onClick={onSelect}
          className={`flex items-center gap-1 px-2.5 py-1.5 rounded-lg text-xs font-semibold transition cursor-pointer ${
            isSelected
              ? 'bg-amber-500 text-slate-950 font-black'
              : 'bg-slate-800 hover:bg-slate-700 text-slate-200'
          }`}
          title="Play in Live Preview placeholder"
        >
          <Play className="w-3 h-3 fill-current" />
          <span>{isSelected ? 'Active Preview' : 'Live Preview'}</span>
        </button>

        <button
          onClick={onInspect}
          className="flex items-center gap-1 px-2.5 py-1.5 bg-indigo-600/90 hover:bg-indigo-500 text-white rounded-lg text-xs font-semibold shadow transition cursor-pointer"
          title="Inspect Codec & Frame Grab in Modal"
        >
          <Sliders className="w-3 h-3" />
          <span>Inspect</span>
        </button>
      </div>
    </div>
  );
};

